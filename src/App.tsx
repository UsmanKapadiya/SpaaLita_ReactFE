import type { FC } from 'react';
import { BrowserRouter as Router, Routes, Route } from 'react-router-dom';
import { ToastContainer } from 'react-toastify';
// Keep this import order: it sets the order of the page stylesheets in the bundle
import Header from './Component/Header/Header';
import HomeScreen from './Pages/Home/HomeScreen';
import ServicesPage from './Pages/Services/ServicesPage';
import ServiceDetailPage from './Pages/Services/ServiceDetailPage';
import { SERVICE_DETAILS } from './Pages/Services/ServicesConstants';
import ContactPage from './Pages/Contact/ContactPage';
import GiftCard from './Pages/GiftCard/GiftCard';
import MonthlySpecial from './Pages/MonthlySpecial/MonthlySpecial';
import BookingPolicy from './Pages/BookingPolicy/BookingPolicy';
import Gallery from './Pages/Gallery/Gallery';
import Cart from './Pages/CartAndCheckout/Cart';
import Checkout from './Pages/CartAndCheckout/Checkout';
import Shop from './Pages/Shop/Shop';
import ProductDetails from './Pages/ProductsDetails/ProductDetails';
import MyAccount from './Pages/MyAccount/MyAccount';
import LostPassword from './Pages/MyAccount/LostPassword';
import ProtectedRoute from './Component/ProtectedRoute/ProtectedRoute';
import OrderReceived from './Pages/CartAndCheckout/OrderReceived';
import ResetPassword from './Pages/MyAccount/ResetPassword';
import NotFound from './Pages/NotFound/NotFound';
import TidioChat from './Component/TidioChat/TidioChat';

const App: FC = () => {
  return (
    <Router>
      <div>
        <Header />
        <main>
          <Routes>
            <Route path="/" element={<HomeScreen />} />
            <Route path="/home" element={<HomeScreen />} />

            {/* Services */}
            <Route path="/services" element={<ServicesPage />} />
            {SERVICE_DETAILS.flatMap((service) =>
              [service.path, ...(service.aliases ?? [])].map((path) => (
                <Route key={path} path={path} element={<ServiceDetailPage key={service.path} service={service} />} />
              ))
            )}

            {/* Shop */}
            <Route path="/giftcard" element={<GiftCard />} />
            <Route path="/shop" element={<Shop />} />
            <Route path="/product/:itemName" element={<ProductDetails />} />
            <Route path="/cart" element={<Cart />} />
            <Route path="/checkout" element={<Checkout />} />
            <Route path="/checkout/order-received/:orderId" element={<OrderReceived />} />

            {/* Info pages */}
            <Route path="/monthly-specials" element={<MonthlySpecial />} />
            <Route path="/contact" element={<ContactPage />} />
            <Route path="/spa-policy/" element={<BookingPolicy />} />
            <Route path="/gallery" element={<Gallery />} />

            {/* Account */}
            <Route
              path="/my-account/*"
              element={
                <ProtectedRoute>
                  <MyAccount />
                </ProtectedRoute>
              }
            />
            <Route path="/my-account/lost-password" element={<LostPassword />} />
            <Route path="/my-account/reset-password/:token" element={<ResetPassword />} />
            {/* reset link format generated by the backend (FRONTEND_URL/reset-password/{token}) */}
            <Route path="/reset-password/:token" element={<ResetPassword />} />

            <Route path="*" element={<NotFound />} />
          </Routes>
        </main>
      </div>
      <ToastContainer />
      <TidioChat />
    </Router>
  );
};

export default App;
